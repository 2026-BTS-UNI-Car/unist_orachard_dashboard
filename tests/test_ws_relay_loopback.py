"""Root-only bounded transport checks, disabled unless explicitly requested.

Generated byte/ACK fixtures over owned socket pairs only. This is not an HTTP
authentication, browser, ROS, Jetson or physical STOP test.
"""
import os
import socket
import threading
import time
import unittest

from dashboard_server.ws_relay import MAX_PENDING_BYTES, relay_sensor_stream


@unittest.skipUnless(os.environ.get("UBTS_TEST_SENSOR_RELAY_LOOPBACK") == "1",
                     "Root must explicitly enable the owned loopback check")
class SensorRelayLoopbackTest(unittest.TestCase):
    def pairs(self):
        client, viewer = socket.socketpair()
        upstream, bridge = socket.socketpair()
        sockets = (client, viewer, upstream, bridge)
        for sock in sockets:
            sock.settimeout(.25)
        self.addCleanup(lambda: [sock.close() for sock in sockets])
        return sockets

    def worker(self, client, upstream, seconds):
        result, errors = [], []
        def serve():
            try:
                result.append(relay_sensor_stream(client, upstream,
                                                  session_deadline=time.time() + seconds))
            except BaseException as error:
                errors.append(type(error).__name__)
        thread = threading.Thread(target=serve, daemon=True)
        thread.start()
        return thread, result, errors

    def test_nonreading_viewer_cannot_block_reverse_ack_or_session_expiry(self):
        client, viewer, upstream, bridge = self.pairs()
        client.setsockopt(socket.SOL_SOCKET, socket.SO_SNDBUF, 4096)
        viewer.setsockopt(socket.SOL_SOCKET, socket.SO_RCVBUF, 4096)
        bridge.setblocking(False)
        started = time.monotonic()
        thread, result, errors = self.worker(client, upstream, 1.0)
        try:
            payload = b"generated-camera-bytes-" * 24000
            sent = 0
            until = time.monotonic() + .35
            while sent < len(payload) and time.monotonic() < until:
                try:
                    sent += bridge.send(payload[sent:])
                except BlockingIOError:
                    time.sleep(.002)
            self.assertGreater(sent, MAX_PENDING_BYTES)
            viewer.sendall(b"generated-ack")
            ack = bytearray()
            until = time.monotonic() + .4
            while len(ack) < len(b"generated-ack") and time.monotonic() < until:
                try:
                    ack.extend(bridge.recv(64))
                except BlockingIOError:
                    time.sleep(.002)
            self.assertEqual(ack, b"generated-ack")
            thread.join(1.25)
            self.assertFalse(thread.is_alive(), "relay must honor the existing session expiry while writes are blocked")
            self.assertFalse(errors)
            self.assertEqual(result[0].reason, "session_expired")
            self.assertLessEqual(result[0].peak_to_client_bytes, MAX_PENDING_BYTES)
            self.assertLess(time.monotonic() - started, 1.8)
        finally:
            client.close()
            upstream.close()
            thread.join(.5)
            self.assertFalse(thread.is_alive(), "owned relay thread cleanup")

    def test_healthy_large_frame_and_reverse_ack_are_exact(self):
        client, viewer, upstream, bridge = self.pairs()
        payload = bytes(range(256)) * 1024
        thread, result, errors = self.worker(client, upstream, 3.0)
        sender_errors = []
        def publish():
            try:
                bridge.settimeout(1)
                bridge.sendall(payload)
                bridge.shutdown(socket.SHUT_WR)
            except BaseException as error:
                sender_errors.append(type(error).__name__)
        sender = threading.Thread(target=publish, daemon=True)
        try:
            viewer.sendall(b"fixture-ack")
            self.assertEqual(bridge.recv(len(b"fixture-ack")), b"fixture-ack")
            sender.start()
            received = bytearray()
            deadline = time.monotonic() + 2
            while len(received) < len(payload) and time.monotonic() < deadline:
                try:
                    chunk = viewer.recv(min(32768, len(payload) - len(received)))
                except socket.timeout:
                    continue
                if not chunk:
                    break
                received.extend(chunk)
            self.assertEqual(received, payload)
            sender.join(.5)
            thread.join(.5)
            self.assertFalse(sender.is_alive() or thread.is_alive())
            self.assertFalse(errors or sender_errors)
            self.assertEqual(result[0].reason, "peer_closed")
        finally:
            client.close()
            upstream.close()
            bridge.close()
            if sender.ident is not None:
                sender.join(.5)
                self.assertFalse(sender.is_alive(), "owned fixture publisher cleanup")
            thread.join(.5)
            self.assertFalse(thread.is_alive(), "owned relay thread cleanup")


if __name__ == "__main__":
    unittest.main()
